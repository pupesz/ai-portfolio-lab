"""
experiment/summary.py
====================

Build results/thesis_numbers_summary.md: formatted Markdown tables and the
architecture parameters, ready to paste into thesis Chapters 5, 6 and 7.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from experiment.core import (
    ALL_STOCKS,
    DEFAULT_LOOKBACK,
    FEATURE_COLS,
    HORIZON,
    INDUSTRIAL_STOCKS,
    IT_STOCKS,
    RESULTS_DIR,
    TRAIN_RATIO,
    VAL_RATIO,
    load_combined,
)
from experiment.models_factory import DROPOUT, HIDDEN
from experiment.trainer import BATCH_SIZE, EPOCHS, GRAD_CLIP, LR, PATIENCE, WEIGHT_DECAY
from experiment.evaluate_all import SEEDS


def _fmt(df: pd.DataFrame, floatfmt="{:.4f}") -> str:
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else floatfmt.format(v))
    return d.to_markdown(index=False)


def build_summary() -> Path:
    metrics = pd.read_csv(RESULTS_DIR / "model_comparison_metrics.csv")
    raw = load_combined()

    # Data audit.
    counts = raw.groupby("symbol").size().to_dict()
    date_min = raw["date"].min().date()
    date_max = raw["date"].max().date()

    lines = []
    A = lines.append
    A("# Thesis Numbers Summary\n")
    A("_Auto-generated by `run_pipeline.py`. All metrics on the 15% chronological test split._\n")

    # ---- Chapter 5: data & architecture ----
    A("## Chapter 5 — Data & Experimental Setup\n")
    A(f"- **Date range:** {date_min} → {date_max}")
    A(f"- **Target:** `target_return_5d = Close(t+{HORIZON}) / Close(t) - 1` (true {HORIZON}-day forward return)")
    A(f"- **Lookback window:** {DEFAULT_LOOKBACK} trading days")
    A(f"- **Split:** chronological {int(TRAIN_RATIO*100)}% / {int(VAL_RATIO*100)}% / "
      f"{int((1-TRAIN_RATIO-VAL_RATIO)*100)}% (train / val / test)")
    A(f"- **Feature scaling:** StandardScaler fit **only on the 70% training split** (no look-ahead bias)")
    A(f"- **Features ({len(FEATURE_COLS)}):** {', '.join(f'`{c}`' for c in FEATURE_COLS)}")
    A(f"- **IT stocks:** {', '.join(IT_STOCKS)}")
    A(f"- **Industrial stocks:** {', '.join(INDUSTRIAL_STOCKS)}\n")

    rowcount = pd.DataFrame(
        {"Ticker": list(counts.keys()), "Rows": list(counts.values())}
    ).sort_values("Ticker")
    A("### Row counts per ticker\n")
    A(rowcount.to_markdown(index=False))
    A("")

    A("### Model architectures & training protocol\n")
    arch = pd.DataFrame([
        {"Parameter": "Hidden / channel width", "TCN": HIDDEN, "LSTM": HIDDEN},
        {"Parameter": "Depth", "TCN": "5 temporal blocks", "LSTM": "2 stacked layers"},
        {"Parameter": "Kernel size", "TCN": 7, "LSTM": "—"},
        {"Parameter": "Dilations", "TCN": "1,2,4,8,16", "LSTM": "—"},
        {"Parameter": "Dropout", "TCN": DROPOUT, "LSTM": DROPOUT},
        {"Parameter": "Head", "TCN": "LayerNorm + Linear", "LSTM": "Dropout + Linear"},
        {"Parameter": "Loss", "TCN": "MSE", "LSTM": "MSE"},
        {"Parameter": "Optimizer", "TCN": "AdamW", "LSTM": "AdamW"},
        {"Parameter": "Learning rate", "TCN": LR, "LSTM": LR},
        {"Parameter": "Weight decay", "TCN": WEIGHT_DECAY, "LSTM": WEIGHT_DECAY},
        {"Parameter": "Batch size", "TCN": BATCH_SIZE, "LSTM": BATCH_SIZE},
        {"Parameter": "Max epochs", "TCN": EPOCHS, "LSTM": EPOCHS},
        {"Parameter": "Early-stop patience", "TCN": PATIENCE, "LSTM": PATIENCE},
        {"Parameter": "Gradient clip (max norm)", "TCN": GRAD_CLIP, "LSTM": GRAD_CLIP},
        {"Parameter": "Seeds (ensemble mean)", "TCN": str(SEEDS), "LSTM": str(SEEDS)},
    ])
    A(arch.to_markdown(index=False))
    A("")
    A(f"> Reported metrics are the mean over {len(SEEDS)} random seeds "
      f"{SEEDS}; `Pred_Std` in the regression table is the mean per-sample "
      f"prediction std across seeds (model uncertainty).")
    A("")

    # ---- Chapter 6: regression & classification ----
    A("## Chapter 6 — Predictive Performance\n")
    A("### Regression metrics (TCN vs LSTM)\n")
    reg = metrics[metrics["Model"].isin(["TCN", "LSTM"])][
        ["Symbol", "Model", "MAE", "MSE", "RMSE", "Pred_Std", "Directional_Acc"]
    ]
    A(_fmt(reg))
    A("")

    A("### Classification metrics — overall & per-class accuracy / F1\n")
    cls_cols = ["Symbol", "Model", "Overall_Acc", "Buy_Acc", "Buy_F1",
                "Hold_Acc", "Hold_F1", "Avoid_Acc", "Avoid_F1"]
    cls = metrics[metrics["Model"].isin(["TCN", "LSTM", "Benchmark"])]
    cls = cls[[c for c in cls_cols if c in cls.columns]]
    A(_fmt(cls))
    A("")

    # ---- Chapter 7: backtesting ----
    A("## Chapter 7 — Backtesting Performance\n")
    bt = metrics[["Symbol", "Model", "CAGR", "Sharpe", "MaxDrawdown"]]
    A(_fmt(bt))
    A("")

    A("### Universe & sector averages\n")
    avg = (metrics.groupby("Model")[["Directional_Acc", "CAGR", "Sharpe", "MaxDrawdown"]]
           .mean(numeric_only=True).reset_index())
    A("**Overall mean (all 10 stocks):**\n")
    A(_fmt(avg))
    A("")
    sect = (metrics.groupby(["Sector", "Model"])[["Directional_Acc", "CAGR", "Sharpe"]]
            .mean(numeric_only=True).reset_index())
    A("**By sector:**\n")
    A(_fmt(sect))
    A("")

    # ---- sensitivity (optional) ----
    thr = RESULTS_DIR / "sensitivity_thresholds.csv"
    lb = RESULTS_DIR / "sensitivity_lookback.csv"
    if thr.exists():
        A("## Sensitivity — decision threshold\n")
        t = pd.read_csv(thr)
        tg = (t.groupby(["Model", "Threshold"])[["Overall_Acc", "Sharpe", "CAGR"]]
              .mean(numeric_only=True).reset_index())
        A(_fmt(tg))
        A("")
    if lb.exists():
        A("## Sensitivity — lookback window\n")
        l = pd.read_csv(lb)
        lg = (l.groupby(["Model", "Lookback"])[["RMSE", "Directional_Acc", "Sharpe"]]
              .mean(numeric_only=True).reset_index())
        A(_fmt(lg))
        A("")

    out = RESULTS_DIR / "thesis_numbers_summary.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


if __name__ == "__main__":
    p = build_summary()
    print(f"Saved {p}")
